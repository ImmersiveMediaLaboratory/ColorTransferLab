import './Logout.scss';
import { useState, useEffect } from 'react';
import { useWebRTC } from '@/Utils/WebRTCProvider';

/******************************************************************************************************************
 ******************************************************************************************************************
 ** FUNCTIONAL COMPONENT
 **
 ** Logout from the admin console
 ******************************************************************************************************************
 ******************************************************************************************************************/
export default function Logout() {
    /**************************************************************************************************************
     **************************************************************************************************************
     ** STATES & REFERENCES & VARIABLES
     **************************************************************************************************************
     **************************************************************************************************************/
    
    /*------------------------------------------------------------------------------------------------------------
    -- STATE VARIABLES
    -------------------------------------------------------------------------------------------------------------*/
    const [completionCode, setCompletionCode] = useState('');

    /*------------------------------------------------------------------------------------------------------------
    -- VARIABLES
    -------------------------------------------------------------------------------------------------------------*/
    const {rtc} = useWebRTC();
    
    /**************************************************************************************************************
     **************************************************************************************************************
     ** HOOKS
     **************************************************************************************************************
     **************************************************************************************************************/
    
    /**************************************************************************************************************
     * Callback for receiving the completion code from the compute node after submission.
     **************************************************************************************************************/
    useEffect(() => {
        rtc.onPutSubmissionRequest = (data) => {
            console.debug("RECV", "[Compute Node] User Study Completion Code received: ", data);
            setCompletionCode(data.completion_code);
        };
    }, [rtc]);

    /**************************************************************************************************************
     **************************************************************************************************************
     ** RENDERING
     **************************************************************************************************************
     **************************************************************************************************************/
    return (
        <div className="logout">
            <div className="logout-success">
                <h2>Thank you for participating!</h2>
                <p>Your answers have been submitted successfully.</p>
                <div className="logout-completion-code-container">
                    Your completion code: <span className="logout-completion-code">{completionCode}</span>
                </div>
            </div>
        </div>
    );
}