import './VideoRenderer.scss';
import {useRef} from 'react';

/******************************************************************************************************************
 ******************************************************************************************************************
 ** FUNCTIONAL COMPONENT
 ** 
 ** Renderer for video files.
 ******************************************************************************************************************
 ******************************************************************************************************************/
export default function VideoRenderer({activeDataType, filePath, setObjInfo}) {
    /**************************************************************************************************************
     **************************************************************************************************************
     ** STATES & REFERENCES & VARIABLES
     **************************************************************************************************************
     **************************************************************************************************************/

    /* ------------------------------------------------------------------------------------------------------------
    -- REFERENCED VARIABLES
    -------------------------------------------------------------------------------------------------------------*/    
    // Ref on the video element
    const videoRef = useRef(null);


    /**************************************************************************************************************
     **************************************************************************************************************
     ** FUNCTIONS
     **************************************************************************************************************
     **************************************************************************************************************/

    /**************************************************************************************************************
     * Called when the video metadata is loaded
     **************************************************************************************************************/
    const handleLoadedMetadata = () => {
        const video = videoRef.current;
        if (!video) return;

        setObjInfo({
            "Duration (s)": video.duration,
            "Resolution": `${video.videoWidth}x${video.videoHeight}`,
        });
    };

    /**************************************************************************************************************
     **************************************************************************************************************
     ** RENDERING
     **************************************************************************************************************
     **************************************************************************************************************/
    return (
        <div
            className="renderer_video"
            style={{ display: activeDataType === "Video" ? "block" : "none" }}
        >
            <video
                src={filePath}
                className="renderer_video_inner"
                width="320"
                height="240"
                controls={true}
                ref={videoRef}
                onLoadedMetadata={handleLoadedMetadata}
            >
                <source type="video/mp4" />
            </video>
        </div>
    )
}